begin;
create table if not exists public.manuscript_import_jobs (
  id uuid primary key,
  -- Retain cleanup metadata briefly even if auth user is deleted.
  owner_id uuid not null,
  status text not null default 'uploading' check (status in ('uploading','queued','processing','succeeded','failed')),
  input_path text not null,
  output_path text,
  attempts integer not null default 0 check (attempts between 0 and 3),
  lease_token uuid,
  lease_until timestamptz,
  available_at timestamptz not null default now(),
  expires_at timestamptz not null default now() + interval '1 hour',
  error_message text,
  created_at timestamptz not null default now()
);
create index if not exists manuscript_import_jobs_expiry on public.manuscript_import_jobs(expires_at);
create index if not exists manuscript_import_jobs_owner on public.manuscript_import_jobs(owner_id,status,expires_at);
alter table public.manuscript_import_jobs enable row level security;
revoke all on public.manuscript_import_jobs from public, anon, authenticated;
grant select, update, delete on public.manuscript_import_jobs to service_role;

insert into storage.buckets(id, name, public, file_size_limit)
values ('manuscript-imports', 'manuscript-imports', false, 4194304)
on conflict (id) do update set public=false, file_size_limit=4194304, allowed_mime_types=null;
-- No browser Storage policy: all paths are generated by authenticated server code.

create or replace function public.reserve_manuscript_import(p_id uuid, p_owner uuid)
returns table(created boolean, job_id uuid) language plpgsql security definer set search_path=public,pg_temp as $$
declare existing public.manuscript_import_jobs%rowtype;
begin
  if p_id is null or p_owner is null or not exists(select 1 from auth.users where id=p_owner) then
    raise exception 'Invalid import identity';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('manuscript-import-admission',0));
  select * into existing from public.manuscript_import_jobs where id=p_id;
  if found then
    if existing.owner_id <> p_owner or existing.expires_at <= clock_timestamp() then raise exception 'Import unavailable'; end if;
    return query select false, p_id; return;
  end if;
  if (select count(*) from public.manuscript_import_jobs where expires_at>clock_timestamp()
      and status in ('uploading','queued','processing') and owner_id=p_owner) >= 2 then
    raise exception using errcode='P0001', message='IMPORT_OWNER_FULL';
  end if;
  if (select count(*) from public.manuscript_import_jobs where expires_at>clock_timestamp()
      and status in ('uploading','queued','processing')) >= 20 then
    raise exception using errcode='P0001', message='IMPORT_QUEUE_FULL';
  end if;
  insert into public.manuscript_import_jobs(id,owner_id,input_path)
    values(p_id,p_owner,p_owner::text||'/'||p_id::text||'/input.docx');
  return query select true,p_id;
end $$;

create or replace function public.claim_manuscript_import()
returns setof public.manuscript_import_jobs language plpgsql security definer set search_path=public,pg_temp as $$
declare chosen uuid;
begin
  perform pg_advisory_xact_lock(hashtextextended('manuscript-import-worker',0));
  update public.manuscript_import_jobs set status='failed',error_message='Tải file bị gián đoạn. Vui lòng chọn lại file.'
    where status='uploading' and created_at<clock_timestamp()-interval '5 minutes';
  update public.manuscript_import_jobs set status='failed', error_message='Tác vụ đã hết số lần thử.', lease_token=null, lease_until=null
    where status='processing' and lease_until<=clock_timestamp() and attempts>=3;
  if exists(select 1 from public.manuscript_import_jobs where status='processing' and lease_until>clock_timestamp()) then return; end if;
  select id into chosen from public.manuscript_import_jobs
    where expires_at>clock_timestamp()+interval '3 minutes' and attempts<3 and available_at<=clock_timestamp()
      and (status='queued' or (status='processing' and lease_until<=clock_timestamp()))
    order by created_at for update skip locked limit 1;
  if chosen is null then return; end if;
  return query update public.manuscript_import_jobs set status='processing',attempts=attempts+1,
    lease_token=gen_random_uuid(),lease_until=clock_timestamp()+interval '180 seconds'
    where id=chosen returning *;
end $$;

create or replace function public.finish_manuscript_import(p_id uuid,p_token uuid,p_outcome text,p_output text default null)
returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
declare updated_count integer;
begin
  if p_outcome is null or p_outcome not in ('succeeded','failed','retry') then raise exception 'Invalid outcome'; end if;
  if p_outcome='succeeded' and not exists(select 1 from public.manuscript_import_jobs
    where id=p_id and p_output=owner_id::text||'/'||id::text||'/result-'||p_token::text||'.json') then
    raise exception 'Invalid output path';
  end if;
  update public.manuscript_import_jobs set
    status=case when p_outcome='retry' and attempts<3 then 'queued' when p_outcome='succeeded' then 'succeeded' else 'failed' end,
    output_path=case when p_outcome='succeeded' then p_output else null end,
    error_message=case when p_outcome='succeeded' then null else 'Không đọc được bản thảo. Vui lòng thử lại với file khác.' end,
    available_at=clock_timestamp()+make_interval(secs=>attempts*30),lease_token=null,lease_until=null
    where id=p_id and status='processing' and lease_token=p_token and lease_until>clock_timestamp() and expires_at>clock_timestamp();
  get diagnostics updated_count=row_count;
  return updated_count=1;
end $$;

revoke all on function public.reserve_manuscript_import(uuid,uuid) from public,anon,authenticated;
revoke all on function public.claim_manuscript_import() from public,anon,authenticated;
revoke all on function public.finish_manuscript_import(uuid,uuid,text,text) from public,anon,authenticated;
grant execute on function public.reserve_manuscript_import(uuid,uuid) to service_role;
grant execute on function public.claim_manuscript_import() to service_role;
grant execute on function public.finish_manuscript_import(uuid,uuid,text,text) to service_role;
commit;
